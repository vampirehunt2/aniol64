;
;  LINE INPUT ROUTINE
;
INPTLNBS:
	DEC	HL		; DELETE A CHARACTER FROM INPUT
	DEC	B
	JP	Z,INPTLNRD
	CALL	PRNTCHRI	; Print (val)
	DEFB	'\'
	INC	C		; Char count
	JP	INPTLINL
INPTLNRD:
	LD	HL,MSGSTARS	; BREAK ENTERED
	CALL	PRNTMSG		; TELL HIM WE GOT IT
	DEC	B		; BREAK AT BEGINNING MEANS BREAK
	JP	Z,INPTEXIT

INPTCRLF:
	CALL	PRNTCRLF	; ON THE NEXT LINE
INPTRQST:
	LD	H,D
	LD	L,E		; PRINT USER'S PROMPT MESSAGE
	CALL	PRNTMSG
	LD	HL,(INPTBUFR)	; INPUT A LINE FROM RECEIVER
	LD	BC,1*256
	CALL	PRNTCHRI	; Print (val)
	DEFB	' '		; OK, WE'RE READY FOR INPUT
INPTLINL:
	LD	(HL),0		; MAINTAIN ENDING ZERO
	CALL	INPTCHAR
INPTLINC:
	CP	BEL
	JP	Z,INPTLNST	; BELL'S OK
	CP	CR
	JP	Z,INPTCRTN	; CARRIAGE RTN IS END OF LINE
	CP	BS
	JP	Z,INPTLNBS	; BACKSPACE IS DELETE
	CP	ETX		; CONTROL C IS ABORT
	JP	Z,INPTLNRD	; FORGET THIS LINE, START OVER
	CP	FF		; FORM FEEDS ARE ECHOED
	JP	Z,INPTLNEC
	CP	' '
	JP	C,INPTLINL	; IGNORE OTHER CONTROL CHARS

;
;  Page 35
;

INPTLNST:
	LD	(HL),A		; STORE THE CHARACTER
	LD	A,B
	CP	LINESYZE
	LD	A,BEL
	JP	NC,INPTLNEC
	INC	B
	OR	C
	LD	C,(HL)
	INC	HL
	LD	A,LF
	CALL	M,PRNTCHRA
	LD	A,C
INPTLNEC:
	CALL	PRNTCHRA	; Ac -> screen  ;ECHO CHARACTER
	JP	INPTLINL
INPTCRTN:
	DEC	B		; CARRIAGE RETURN AT BEGINNING
	JP	Z,INPTCRLF	; GETS ANOTHER TURN
INPTEXIT:
	LD	HL,(INPTBUFR)
	DEC	HL
	CALL	PRNTCRLF
	SUB	B		; SET CONDITION CODES
	CCF
	SBC	A,A		; NS=NC=Z = NON-EMPTY LINE
	RET

MSGSTARS:
	DEFB	'***',0

