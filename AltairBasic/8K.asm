;  Page 25
;

;
;  RE-INITIALIZATION ROUTINES
;
NEWSTM:
	RET	NZ		; NEW COMMAND
CLEARPGM:
	LD	HL,(PROGBASE)	; CLEAR PROGRAM
	XOR	A
	LD	(HL),A
	INC	HL
	LD	(HL),A
	INC	HL
NEWLOAD:
	LD	(VARTABLE),HL
CLEARSET:
	CALL	CLEARPCN	; CLEAR PROGRAM POINTERS
CLEARVST:
	LD	(PROGCNTR),HL	; UPDATE PROGRAM COUNTER
	CALL	CLEARVAR	; CLEAR VARIABLES
CLEARSTK:
	POP	BC		; RESET STACK,
	LD	HL,(STCKBASE)
	LD	SP,HL
	LD	HL,0-LINESYZE-3
	ADD	HL,SP
	LD	SP,HL		; CREATE INPUT BUFFER
	LD	(INPTBUFR),HL
	LD	HL,(STRGBASE)	; CLEAR STRING TEMPORARIES,
	INC	HL
	LD	(STRGTMPP),HL
	LD	HL,0
	PUSH	HL
	LD	(PROGCNTS),HL	; SET NO CONTINUE
	LD	HL,(PROGCNTR)
	PUSH	BC
	RET

CLEARVAR:
	LD	HL,(VARTABLE)	; CLEAR ALL VARIABLES
	LD	(MATTABLE),HL
	LD	(FREELIMT),HL
	LD	HL,(STRGBASE)
	LD	(STRGFREE),HL
	RET

CLEARPCN:
	LD	HL,0		; CLEAR PROGRAM POINTERS
	LD	(PROGCNTS),HL
	LD	HL,(PROGBASE)
	DEC	HL
	LD	(HL),0		; END OF LINE -1
	LD	(PROGCNTR),HL
	XOR	A

;
;  Page 26
;

;
;  RESTORE:  REWIND DATA STATEMENTS
;
RESSTM:
	JP	Z,RESSTMDF	; RESTORE STATEMENT
	CALL	SCANLINN
	PUSH	HL
	CALL	LINESRCH
	JP	NC,ERRAUS
	POP	HL
	EX	DE,HL
	JP	RESSTMBU
RESSTMDF:
	EX	DE,HL		; DEFAULT IS RESTORE TO BEGINING
	LD	HL,(PROGBASE)
RESSTMBU:
	DEC	HL		; BACK UP BEFORE LINE
RESDTPTR:
	LD	(CURDATAP),HL	; SET DATA POINTER
	EX	DE,HL
	RET

;
;  CLEAR:  CLEAR VARIABLES, REALLOCATE STRING SPACE
;
CLRSTM:
	JP	Z,CLEARVST	; CLEAR STATEMENT
	CALL	VALINTDE
	DEC	HL		; Bscan -
	CALL	SCANNXT		; Bscan ,
	RET	NZ
	PUSH	HL
	LD	HL,(STRGBASE)
	LD	A,L
	SUB	E
	LD	E,A
	LD	A,H
	SBC	A,D
	LD	D,A
	JP	C,ERRASN
	LD	HL,(VARTABLE)
	LD	BC,40
	ADD	HL,BC
	CALL	CMHLLTDE
	JP	NC,ERRAOM
	EX	DE,HL
	LD	(STCKBASE),HL
	POP	HL
	JP	CLEARVST

