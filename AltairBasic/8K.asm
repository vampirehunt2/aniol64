EDISTMNX:
	CALL	EDISTMCH	; OK MASTER, TELL ME WHAT TO DO
	CP	' '		; MOVE ALONG
	JP	Z,EDISTMAD
	CALL	ALPHACHA	; CONVERT LOWER TO UPPER
	CP	'D'		; DELETE
	JP	Z,EDISTMDL
	CP	'I'		; INSERT
