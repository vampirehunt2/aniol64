;
SCANLPRZ:
	LD	BC,0		; DEFAULT SECOND IS FIRST
SCANLPRM:
	CALL	NZ,SCANLINN	; DEFAULT FIRST IS IN DE
	PUSH	AF
	LD	A,B
	OR	C		; ZERO DEFAULT IS FIRST PARAMETER
	JP	NZ,SCANLPR1
	LD	B,D
	LD	C,E
SCANLPR1:
	POP	AF
	EX	DE,HL
	EX	(SP),HL		; PUT FIRST ONTO STACK
	PUSH	HL
	EX	DE,HL
	LD	D,B
	LD	E,C
	RET	Z
	CP	KEYDIV		; SEPARATOR MUST BE '/'.
	JP	Z,SCANLPR2
	CALL	SCANNXTV	; Bscan (val)
	DEFB	','		;   OR ','
	DEC	HL
SCANLPR2:
	LD	DE,0FFFFH	; EMPTY SECOND OPERAND = END
	CALL	SCANNXT		; Bscan ,
	RET	Z

