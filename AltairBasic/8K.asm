	JP	Z,ERRASN
	SUB	KEYON
	LD	B,A		; SAVE FLAG
	CALL	SCANNXT		; Bscan +
	POP	AF		; WHICH OPTION
	CP	KEYGTO
	JP	Z,SETSTMGT	; GOTO
	CP	KEYPRT
	JP	NZ,ERRASN
