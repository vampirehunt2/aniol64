;  Page 27
;

;
;  LOW-LEVEL CHARACTER I/O ROUTINES
;
PRNTCHRI:
	EX	(SP),HL
	LD	A,(HL)
	INC	HL
	EX	(SP),HL
PRNTCHRA:
	PUSH	AF		; TRANSMIT CHARACTER
	LD	A,(PRINTFLG)
	OR	A
	JP	NZ,POPAFRET
	POP	AF
	PUSH	AF
	CP	' '
	JP	C,PRNTCHRW
