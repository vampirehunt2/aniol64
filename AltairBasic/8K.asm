;
;  SCAN ONE CHARACTER AND CLASSIFY
;
SCANNXTV:
	LD	A,(HL)		; SCAN CURRENT BYTE,
	EX	(SP),HL
	CP	(HL)		; VERIFY MATCH,
	INC	HL
	EX	(SP),HL
	JP	NZ,ERRASN	; SQUAWK ABOUT SYNTAX ERROR
SCANNXT:
	INC	HL		; SCAN FOR NEXT NON-BLANK CHAR
	LD	A,(HL)		; C=NUMERIC CHARACTER
	CP	':'		; Z=END OF STATEMENT
	RET	NC
	CP	' '
	JP	Z,SCANNXT
	CP	'0'
	CCF
	INC	A
	DEC	A
	RET

;
;  Page 18
;

;
;  TEST FOR ALPHABETIC CHARACTER
;
ALPHACHK:
	LD	A,(HL)		; TEST FOR ALPHABETIC CHARACTER
ALPHACHA:
	CP	'z'+1		; LOWER CASE
	RET	NC
	CP	'a'		; LOWER CASE
	JP	NC,ALPHACHL
	CP	'Z'+1		; C=ALPHABETIC
	RET	NC
	CP	'A'		; UPPER CASE
	CCF
	RET
ALPHACHL:
	ADD	A,'A'-'a'	; CONVERT LOWER TO UPPER
	RET

;
;  MATCH CHARACTER OF BUFFER AGAINST CHARACTER IN A
;
CHARMTCH:
	XOR	(HL)		; MAKE MATCH TEST
	RET	Z		; Z-SUCCESS]
	CP	'a'-'A'		; LOWER CASE - UPPER CASE
	RET	NZ		; NOT LOWER-UPPER DIFFERENCE
	CALL	ALPHACHK	; ALPHABETIC?
	SBC	A,A
	INC	A		; Z=C,S=0
	RET

;
;  CHECK TYPE OF EXPRESSION	       LEN     CHAR
;            RETURNS:  S => INTEGER	2	%
;		       Z => STRING	3	$
;		      PO => SINGLE	4	@
;		      NC => DOUBLE	8	#
TYPECHK:
	LD	A,(TYPEFLG)
TYPECHKA:
	CP	TYPESING+1
	DEC	A
	DEC	A
	DEC	A
	OR	A
	SCF
	RET

