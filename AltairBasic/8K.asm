	CALL	SYSKEYIN	; RECEIVE A CHARACTER
	JP	Z,INPTCHAR	; WAIT FOR ONE
	CP	SI
	RET	NZ
	LD	A,(PRINTFLG)
	CPL
	LD	(PRINTFLG),A
	JP	INPTCHAR

