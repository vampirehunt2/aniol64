	CP	B
	JP	NC,EDISTMER	; NO MORE, TERMINATE SEARCH
	CALL	ALPHACHK	; FETCH CHARACTER IN STANDARD CASE
	CP	E
	JP	Z,EDISTMNX	; GOTTA MATCH?
	CALL	PRNTCHRA	; Ac -> screen  ;LIST FAILURES
	INC	C
	INC	HL
	LD	E,D
	JP	EDISTMSL	; AND KEEP LOOKING

