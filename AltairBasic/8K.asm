CO:	IN	A,(10H)		; Read console status
	AND	2		; If not ready
	JP	Z,CO		; Keep waiting
	LD	A,C		; Get character
	OUT	(11H),A		; And print it
	RET

CINB:	IN	A,(10H)		; Read console status
	AND	1		; Check if character available
	RET	Z		; Return if not with carry clear
	IN	A,(11H)		; Get character
	SCF			; And set carry flag
	RET

DCLR:				; Not implemented yet
	RET

XCO:				; Not implemented yet
	RET

;
;  NON-BLOCKING INPUT
;   CHAR IN AC IF NOT ZERO
;   ZERO SET IF NONE
;
SYSKEYIN:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	CALL	CINB		; Get char
	JP	NC,SYSKEYNONE
	CP	0
	JP	Z,CLEARSCREEN
	CP	1FH		; Us to bring to 14
	JP	Z,GOMONITOR
SYSKEYINRET:
	POP	HL
	POP	DE
	POP	BC
	RET
SYSKEYNONE:
	SUB	A		; Set zero
	JP	SYSKEYINRET
CLEARSCREEN:
	CALL	DCLR		; Clear screen
	JP	SYSKEYNONE
GOMONITOR:
	RST	8*1		; About using us (^_)
	NOP
	NOP
;
;  SEND AC TO SCREEN
;
SYSDISPL:
	PUSH	AF
	PUSH	BC
	PUSH	DE

;
; Page 2
;

	PUSH	HL
	LD	C,A
	CALL	CO		; C to screen
	LD	A,(P3010)	; Print on the 3010 if zero
	AND	A
	CALL	Z,XCO		; Yes print
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET
;
;  CHECK FOR BREAK REQUEST
;   SET ZERO TO BREAK
;
SYSBREAK:
	CALL	SYSKEYIN
	JP	Z,NOBREAK
	SUB	A
	RET
NOBREAK:
	LD	A,1
	OR	A
	RET
;
;  DELAY
;
SYSWAIT:
	RET
;
;  RETURN TO MONITOR
;
MONITOR EQU	0B400H
SYSQUIT:
	JP	MONITOR

