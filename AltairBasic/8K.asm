	LD	A,(HL)		; EXPAND KEYWORD
	RLCA
	AND	A		; HIGH-ORDER TO CARRY
	RRA
	CALL	LISEDIST	; STUFF THIS CHARACTER
	INC	HL
	JP	NC,LISEDIKY	; DO THEM ALL
	LD	A,C
	LD	HL,KEYLSAH*256+KEYLSAL
	CALL	LISEDISB	; OPTIONAL BLANK AFTER KEYWORD
	JP	LISEDIKD

