	DEFB	KEYMID		; ENTER POINTING TO 'MID$'
	CALL	SCANNXTV	; Bscan (val)
	DEFB	'('
	CALL	VARSCAN		; SCAN VARIABLE TO UPDATE
	CALL	CSTRING		; MAKE SURE IT'S A STRING
	PUSH	DE		; SAVE REFERENCE
	PUSH	HL
