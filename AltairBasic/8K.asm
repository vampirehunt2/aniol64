;
;  LIST COMMAND PROCESSOR
;
LISSTM:
	LD	DE,0		; LIST COMMAND
	LD	BC,0FFFFH	; TOTAL DEFAULT IS ENTIRE FILE
	JP	Z,LISSTMSC
	LD	BC,0		; ELSE DEFAULT IS ONLY ONE LINE
LISSTMSC:
	CALL	SCANLPRM	; SCAN LINE PARAMETERS
	JP	NZ,ERRASN
	EX	(SP),HL
	EX	DE,HL
	PUSH	HL
	CALL	LINESRCH
	PUSH	BC
LISSTMLP:
	POP	BC		; MOVE ON TO NEXT LINE
	POP	DE
	POP	HL
	CALL	SYSBREAK	; ALLOW BREAK
	JP	Z,EXECUTEB
	PUSH	BC
	EX	(SP),HL
	CALL	LINELINK
	JP	Z,POPHLRET	; END OF PROGRAM, QUIT
	PUSH	DE
	PUSH	BC
	PUSH	HL		; SAVE TEXT FOR LATER
	LD	C,(HL)		; FETCH LINE NUMBER
	INC	HL
	LD	B,(HL)
	LD	H,B
	LD	L,C
	EX	DE,HL
	CALL	CMHLLTDE
	JP	C,LISSTMXT	; LAST LINE REACHED?
	CALL	PRNTCRLF	; LIST CURRENT LINE
	EX	DE,HL
	CALL	PRINTINT	; PRINT LINE NUMBER
	CALL	PRNTCHRI	; Print (val)
	DEFB	' '		; FOLLOWED BY BLANK
	POP	HL
	CALL	LISEDIXP	; EXPAND TEXT
	CALL	PRNTMSG		; AND PRINT IT
	LD	HL,0+LINESYZE+3
	ADD	HL,SP
	LD	SP,HL		; DEALLOCATE EXPANDED TEXT
	JP	LISSTMLP

;
;  Page 38
;
LISSTMXT:
	POP	HL
POPHL3RT:
	POP	HL
	POP	HL
POPHLRET:
	POP	HL
	RET


;
;  EXPAND KEYWORDS IN LINE / INVERSE OF KEYSCAN
;
LISEDIXP:
	LD	C,LINESYZE/2	; SPACE ENOUGH TO EXPAND LINE?
	CALL	SPACESTK
	EX	DE,HL		; SAVE POINTER TO LINE TO EXPAND
	POP	BC		; AND CALLER
	LD	HL,0-LINESYZE-3
	ADD	HL,SP
	LD	SP,HL		; CREATE TEXT BUFFER ON STACK
	PUSH	BC		; PUT BACK CALLER
	EX	DE,HL
	INC	HL
	INC	HL		; Plus 2
	PUSH	HL		; SAVE TEXT POINTER
	LD	HL,4		; CREATE POINTER TO EXPAND TEXT
	ADD	HL,SP
	EX	DE,HL
	LD	B,LINESYZE	; INITIALIZE LENGTH COUNTER
	JP	LISEDIKD
LISEDISC:
	CALL	LISEDIST	; STUFF ONE CHARACTER OF LINE
LISEDIKD:
	POP	HL		; DO REST OF LINE
	LD	A,(HL)
LISEDINC:
	INC	HL
	CP	':'
	JP	NZ,LISEDIKT
	LD	A,(HL)
	CP	KEYELS		; :ELSE BECOMES ELSE
	JP	Z,LISEDINC
	LD	A,':'
LISEDIKT:
	AND	A		; MOVE HIGH ORDER INTO S-FLAG
	JP	Z,LISEDIXT
	PUSH	HL
	JP	P,LISEDISC
	LD	C,A

;
;  Page 39
;

	LD	HL,KEYLSBH*256+KEYLSBL
	CALL	LISEDISB	; OPTIONAL BLANK BEFORE KEYWORD
	LD	HL,KEYWORDS	; SEARCH FOR KEYWORD
	JP	LISEDIKS
