	JP	C,ERRASN
	LD	H,D
	LD	L,E		; HL=10*DE
	ADD	HL,DE
	ADD	HL,HL
	ADD	HL,DE
	ADD	HL,HL
	POP	AF
	SUB	'0'		; GET VALUE OF NEXT DIGIT

;
;  Page 20
;

	LD	E,A
	LD	D,000H
	ADD	HL,DE		; AND ADD IT ON
	EX	DE,HL
	POP	HL
	JP	SCANLINL

;
;  Page 21
;

;
;  SEARCH FOR A GIVEN LINE NUMBER
;
LINESRCH:
	LD	HL,(PROGBASE)	; LOOK FOR LINE NUMBER IN DE
LINESRCL:
	PUSH	HL		; C=LINE FOUND
	CALL	LINELINK	; BC=LINE LOCATION, IF FOUND
	JP	Z,POPHLRET	; =NEXT LINE, IF NOT FOUND
	PUSH	BC		; ADDRESS OF NEXT LINE
	LD	A,(HL)		; GET NUMBER OF CURRENT LINE
	INC	HL
	LD	H,(HL)		; (from HL,MA)
	LD	L,A
	CALL	CMHLLTDE
	POP	HL		; HL=NEXT LINE
	POP	BC
	CCF
	RET	Z
	JP	NC,LINESRCL
	LD	H,B
	LD	L,C
	CCF
	RET

;
;  LINK TO NEXT LINE
;
LINELINK:
	PUSH	HL		; FIND ADDRESS OF NEXT LINE
	LD	C,(HL)		; Z=END OF PROGRAM
	INC	HL
	LD	B,(HL)
	INC	HL
	EX	(SP),HL
	ADD	HL,BC		; ADD LENGTH TO ADDRESS
	EX	(SP),HL
	LD	A,B
	OR	C
	POP	BC
	RET

;
;  Page 22
;

;
;  INSERT/REPLACE LINE OF PROGRAM
;
LINEINS:
	PUSH	DE		; DE=LINE NUMBER
	CALL	NC,KEYSCAN	; C=ALREADY KEY-SCANNED
	CALL	SCANNXT		; Bscan , NC=MUST BE KEY-SCANNED
	POP	DE
	PUSH	HL		; HL=TEXT TO INSERT
	PUSH	DE
	PUSH	BC		; BC=LENGTH OF TEXT
	PUSH	AF		; Z=DELETE, NO REPLACE
	CALL	LINESRCH	; LOOK FOR LINE
	PUSH	BC		; SAVE LOCATION
	CALL	C,LINEDEL	; DELETE IF PRESENT
	POP	DE
	POP	AF
	JP	Z,POPHL3RT	; EXIT IF NOTHING MORE
	LD	HL,(FREELIMT)	; PULL APART FOR NEW LINE
	EX	(SP),HL
	POP	BC
	PUSH	HL
	ADD	HL,BC
	CALL	COPYCHK
	EX	DE,HL
	POP	BC
	LD	(HL),C		; BEGINNING OF NEW LINE
	INC	HL
	LD	(HL),B
	INC	HL
	POP	DE
	LD	(HL),E		; INSERT LINE NUMBER
	INC	HL
	LD	(HL),D
	INC	HL
	EX	DE,HL
	POP	HL		; RECOVER TEXT POINTER
LINEINSL:
	LD	A,(HL)		; INSERT TEXT OF NEW LINE
	LD	(DE),A
	INC	HL
	INC	DE
	OR	A
	JP	NZ,LINEINSL
	JP	LINEDELU


;
;  Page 23
;

;
;  DELETE TEXT FROM PROGRAM
;
LINEDEL:
	EX	DE,HL		; BC=BEGINNING OF TEXT TO REMOVE
	LD	A,C
	SUB	E		; COMPUTE NETATIVE OF
	LD	L,A		; NUMBER OF BYTES DELETED
	LD	A,B
	SBC	A,D
	LD	H,A
	PUSH	HL
	LD	HL,(FREELIMT)	; HL=BEGINNING OF TEXT SURVIVING
LINEDELL:
	LD	A,(DE)
	LD	(BC),A
	INC	BC
	INC	DE
	CALL	CMHLLTDE
	JP	NC,LINEDELL
	POP	BC
LINEDELU:
	LD	HL,(FREELIMT)	; UPDATE DATA POINTERS
	ADD	HL,BC		; BC=INCREMENT
	LD	(FREELIMT),HL
	LD	HL,(MATTABLE)
	ADD	HL,BC
	LD	(MATTABLE),HL
	LD	HL,(VARTABLE)
	ADD	HL,BC
	LD	(VARTABLE),HL
	JP	CLEARPCN

;
;  MAKE SIXTEEN BIT COMPARISON
;
CMHLLTDE:
	LD	A,H		; COMPARE DE VS HL
	SUB	D		; C=HL<DE
	RET	NZ
	LD	A,L
	SUB	E
	RET

;
;  Page 24
;

;
;  MOVE LONG TO HIGHER ADDRESS
;
COPYCHK:
	CALL	SPACECHK
COPYTEXT:
	PUSH	BC		; COPY SECTION DE-BC TO AREA
	EX	(SP),HL		; ENDING AT HL
	POP	BC
COPYTXTL:
	CALL	CMHLLTDE
	LD	A,(HL)
	LD	(BC),A
	RET	Z
	DEC	BC
	DEC	HL
	JP	COPYTXTL

;
;  CHECK SPACE FOR STACK ALLOCATION
;
SPACESTK:
	PUSH	HL		; VERIFY STACK HAS ROOM ENOUGH
	LD	HL,(FREELIMT)	; C=NUMBER OF WORKS NEEDED
	LD	B,000H
	ADD	HL,BC
	ADD	HL,BC
	CALL	SPACECHK
	POP	HL
	RET

;
;  CHECK SPACE FOR PROGRAM OR VARIABLE ALLOCATION
;
SPACECHK:
	PUSH	DE		; CHECK THAT ENOUGH SPACE IS LEFT
	EX	DE,HL		; ON STACK ABOVE HL
	LD	HL,-38
	ADD	HL,SP
	CALL	CMHLLTDE
	EX	DE,HL
	POP	DE
	RET	NC
ERRAOM:
	LD	E,ERRNOM-ERRN
	JP	ERRMSG

