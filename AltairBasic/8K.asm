	LD	HL,(CURSPOS)	; LINE TOO LONG?
	LD	A,H
	ADD	A,L
	LD	A,L
	POP	HL
	CALL	C,PRNTCRLF
	INC	A
	LD	(CURSPOS),A
PRNTCHRW:
