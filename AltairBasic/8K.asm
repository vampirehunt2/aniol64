	LD	DE,0FFFFH	; DELETE COMMAND
	CALL	SCANLPRZ
	EX	(SP),HL		; SAVE SCAN POINTER
	EX	DE,HL
	CALL	CMHLLTDE	; VERITY  FIRST<=LAST
	JP	C,ERRASN
	PUSH	HL
	CALL	LINESRCH	; LOOK FOR FIRST LINE
	POP	DE
	PUSH	BC
	CALL	LINESRCH	; LOOK FOR LAST LINE
	POP	BC
	CALL	LINEDEL
	POP	HL
	RET

