;
;  LEXICAL SCANNER / KEYWORD RECOGNITION
;
KEYSCAN:
	LD	C,5		; SCAN INPUT LINE FOR KEYWORDS,
	LD	D,H		; CONDENSE LINE ON TOP OF SELF
	LD	E,L
	DEC	HL		; Bscan -
	PUSH	HL
	CALL	SCANNXT		; Bscan +
KEYSCANL:
	LD	A,(HL)
	CP	' '
	JP	Z,KEYSCANH	; DELETE BLANKS
	LD	B,A
	CP	'"'
	JP	Z,KEYSCANI	; SWALLOW WHOLE STRING
	OR	A
	JP	Z,KEYSCANX
	CP	'0'		; NON-KEYWORD
	JP	C,KEYSCANK
	CP	'<'		;   SO WE DON'T SCAN
	JP	C,KEYSCANP
KEYSCANK:
	PUSH	BC		; SCAN FOR MATCHING KEYWORD
	PUSH	DE
	PUSH	HL
	AND	00FH		; HASH CHARACTER
	LD	E,A
	LD	D,0
	LD	HL,KEYWADDS	; ADDRESS C'SPONDING KEYWORDS
	ADD	HL,DE
	ADD	HL,DE
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	EX	DE,HL
	JP	KEYSCANB

KEYSCANZ:
	LD	A,(DE)
	OR	A
	JP	P,KEYSCANN
KEYSCANM:
	LD	A,B		; MATCH, GET SYMBOL NUMBER
	OR	080H
	JP	KEYSCANF
KEYSCANN:
	INC	HL		; ADDRESS NEXT CHAR IN LINE
	INC	DE
	INC	C
KEYSCANC:
	LD	A,(DE)		; COMPARE LINE WITH KEYWORD
	AND	07FH
	CALL	CHARMTCH	; COMPARE CHARACTERS

;
;  Page 32
;

	JP	Z,KEYSCANZ
	LD	A,C		; MATCH ENOUGH YET?
	CP	3
	JP	C,KEYSCANA

	CALL	ALPHACHK	; STOP ON BREAK CHAR OK
	DEC	HL
	JP	NC,KEYSCANM
KEYSCANA:
	EX	DE,HL
KEYSCANW:
	OR	(HL)		; SKIP OVER REST OF KEYWORD
	INC	HL
	JP	P,KEYSCANW
	XOR	B
KEYSCANB:
	LD	B,(HL)		; GET CODE FOR KEYWORD
	INC	HL
	EX	DE,HL
	POP	HL		; RESTORE STARTING POSITION
	PUSH	HL
	LD	C,0
	JP	P,KEYSCANC
	LD	A,(HL)		; NO MATCH, GET CHARACTER
KEYSCANF:
	POP	DE		; RECOVER OUTPUT POINTER
	POP	DE
	POP	BC
	LD	B,':'		; CHECK SPECIAL PROCESSING
	CP	KEYELS
	JP	NZ,KEYSCAND
	EX	DE,HL
	LD	(HL),B		; INSERT COLON BEFORE ELSE
	EX	DE,HL
	INC	DE
	INC	C
KEYSCAND:
	CP	KEYDAT
	JP	Z,KEYSCANI
	LD	B,0
	CP	KEYREM
	JP	Z,KEYSCANI
	CP	KEYCLD		; Pass file name in load and save
	JP	Z,KEYSCANI
	CP	KEYCSV
KEYSCANI:
	CALL	Z,KEYSCANV
	OR	A
	JP	Z,KEYSCANX
KEYSCANP:
	LD	(DE),A		; INSERT SYMBOL IN MEMORY
	INC	DE
	INC	C
KEYSCANH:
	INC	HL
	JP	KEYSCANL

;
;  Page 33
;

KEYSCANX:
	POP	HL		; EXIT KEYWORD TRANSLATION
	LD	(DE),A		; END OF STATEMENT
	INC	DE
	LD	(DE),A		; END OF 'PROGRAM'
	INC	DE
	LD	(DE),A
	LD	B,A		; LENGTHIN BC
	RET

;
;  COPY BUFFER TEXT WITHOUT PROCESSING
;
KEYSCANV:
	LD	(DE),A		; COPY TEXT VERBATIM TO STOPPER
	INC	C
	INC	DE
	INC	HL
	LD	A,(HL)
	OR	A
	RET	Z
	CP	B
	RET	Z
	CP	'"'		; STRING WITHIN TEXT?
	JP	NZ,KEYSCANV
	PUSH	BC
	LD	B,A
	CALL	KEYSCANV
	POP	AF
	LD	B,A
	LD	A,(HL)
	OR	A		; STRING TERMINATE ON END OF LINE?
	RET	Z
	JP	KEYSCANV

